"""Writes reports/build_report.md and reports/review_queue.csv (deterministic, no timestamps)."""

from __future__ import annotations

import csv
from collections import Counter, defaultdict
from pathlib import Path

from .merge import ROLES, BuildResult

REVIEW_FIELDS = ["source_id", "source_record_id", "record_name", "equipment", "exercise_id",
                 "candidate_exercise_id", "candidate_name", "score", "reason"]


def _table(header: list[str], rows: list[list]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    for r in rows:
        out.append("| " + " | ".join("" if v is None else str(v).replace("|", "\\|") for v in r) + " |")
    return out


def write_review_queue(res: BuildResult, path: Path) -> None:
    with path.open("w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=REVIEW_FIELDS, lineterminator="\n")
        w.writeheader()
        for row in res.review_queue:
            w.writerow(row)


def write_build_report(res: BuildResult, tables: dict, path: Path) -> None:
    tax = res.tax
    L: list[str] = ["# Build report", "",
                    "Generated by `make build`. Deterministic: no timestamps except the snapshot dates of the sources.", ""]

    # ---- sources
    L += ["## Sources", ""]
    rows = []
    for sid in tax.config["sources"]:
        s = tax.sources[sid]
        recs = [r for r in res.records if r.source_id == sid]
        rows.append([sid, s["name"], s["license"], s["version"], s["retrieved_at"], len(recs)])
    L += _table(["source", "name", "license", "version", "retrieved", "records"], rows) + [""]

    # ---- merge counts
    L += ["## Merge", ""]
    rows = []
    for sid in tax.config["sources"]:
        c = Counter()
        for r in res.records:
            if r.source_id != sid:
                continue
            a = res.assignments[r.ref]
            if not a.exercise_id:
                c["skipped"] += 1
            elif a.in_review:
                c["new, in review"] += 1
            elif a.match_method == "new":
                c["new"] += 1
            else:
                c["merged"] += 1
                c[f"merged:{a.match_method}"] += 1
        merged_detail = ", ".join(f"{m} {c[f'merged:{m}']}" for m in ("exact", "normalized", "fuzzy", "manual") if c[f"merged:{m}"])
        rows.append([sid, sum(v for k, v in c.items() if ":" not in k), c["new"], c["new, in review"],
                     f"{c['merged']}" + (f" ({merged_detail})" if merged_detail else ""), c["skipped"]])
    L += _table(["source", "records", "new exercises", "new, in review queue", "merged into an existing exercise", "skipped"], rows)
    n_multi = sum(1 for recs in res.ex_records.values() if len({r.source_id for r in recs}) > 1)
    n_multi_rec = sum(1 for recs in res.ex_records.values() if len(recs) > 1)
    L += ["",
          f"- Exercises: **{len(res.exercises)}** "
          f"({n_multi} backed by more than one source, {n_multi_rec} by more than one record).",
          f"- Review queue: **{len(res.review_queue)}** records (`reports/review_queue.csv`, exercises have `needs_review=1`): "
          + ", ".join(f"{n} {r}" for r, n in sorted(Counter(q["reason"] for q in res.review_queue).items(),
                                                    key=lambda kv: (-kv[1], kv[0]))) + ".",
          f"- Variations linked with `variation_of`: {sum(1 for e in res.exercises.values() if e['variation_of'])}.",
          f"- Exercises with instructions: {sum(1 for e in res.exercises.values() if e['instructions'])}.",
          f"- Exercises with a German name: {sum(1 for e in res.exercises.values() if e['name_de'])}.",
          f"- Movement pattern set: {sum(1 for e in res.exercises.values() if e['movement_pattern'])}; "
          f"laterality set: {sum(1 for e in res.exercises.values() if e['laterality'])} (NULL where no explicit rule applies).",
          ""]

    # ---- categories
    L += ["## Exercises per category", ""]
    cat = Counter(e["category"] for e in res.exercises.values())
    L += _table(["category", "exercises"], [[k, cat[k]] for k in sorted(cat, key=lambda k: (-cat[k], k))]) + [""]

    # ---- muscle groups
    L += ["## Exercises per muscle group", "",
          "From the `exercise_muscle_groups` view: an exercise counts for a group once, at its highest role there.", ""]
    grp: dict[str, Counter] = defaultdict(Counter)
    per_ex: dict[tuple[str, str], int] = {}
    for m in res.exercise_muscles:
        g = tax.group_of(m["muscle_id"])
        k = (m["exercise_id"], g)
        per_ex[k] = min(per_ex.get(k, 9), ROLES.index(m["role"]))
    for (ex_id, g), rank in per_ex.items():
        grp[g][ROLES[rank]] += 1
    groups = [m["id"] for m in sorted(tax.muscles.values(), key=lambda m: m["id"]) if m["level"] == "group"]
    rows = [[g, tax.muscles[g]["name_de"], grp[g]["primary"], grp[g]["secondary"], grp[g]["stabilizer"],
             sum(grp[g].values())] for g in groups]
    L += _table(["group", "name_de", "primary", "secondary", "stabilizer", "total"], rows) + [""]
    spec = Counter(m["muscle_id"] for m in res.exercise_muscles if tax.muscles[m["muscle_id"]]["level"] == "muscle")
    L += ["Specific muscles used: " + (", ".join(f"`{k}` {spec[k]}" for k in sorted(spec)) or "none"), ""]

    # ---- authoritative sources
    auth = [a for a in tax.config.get("authoritative_sources") or [] if a in tax.sources]
    if auth:
        L += ["## Reviewed muscle mappings", "",
              f"For exercises covered by {', '.join(f'`{a}`' for a in auth)} its muscle list is final "
              "(instead of the majority vote). Other sources' claims that it does not keep are listed here; "
              "they stay in `exercise_muscle_evidence`.", ""]
        rows = []
        kept = defaultdict(set)
        for m in res.exercise_muscles:
            kept[m["exercise_id"]].add(m["muscle_id"])
        for ex_id in sorted(res.ex_records):
            recs = res.ex_records[ex_id]
            if not any(r.source_id in auth for r in recs):
                continue
            dropped = sorted({f"{r.source_id}: {mid} ({role})" for r in recs if r.source_id not in auth
                              for mid, role in r.claims.items()
                              if mid not in kept[ex_id] and tax.group_of(mid) not in kept[ex_id]
                              and not any(tax.group_of(k) == mid for k in kept[ex_id])})
            rows.append([f"`{ex_id}`", res.exercises[ex_id]["name_en"], "; ".join(dropped) or "-"])
        L += _table(["exercise", "name", "claims not kept"], rows) + [""]

    # ---- no secondary
    roles_by_ex: dict[str, set[str]] = defaultdict(set)
    for m in res.exercise_muscles:
        roles_by_ex[m["exercise_id"]].add(m["role"])
    no_sec = sorted(e for e in res.exercises if "secondary" not in roles_by_ex[e])
    L += ["## Exercises without secondary muscles", "",
          f"{len(no_sec)} of {len(res.exercises)} exercises have no secondary muscle.", "",
          "<details><summary>List</summary>", "", ", ".join(f"`{e}`" for e in no_sec), "", "</details>", ""]

    # ---- licenses
    # ---- images
    L += ["## Images", ""]
    with_pos = defaultdict(set)
    img_src = Counter()
    for img in res.exercise_images:
        with_pos[img["exercise_id"]].add(img["position"])
        img_src[(img["source_id"], img["position"])] += 1
    both = sum(1 for p in with_pos.values() if p == {"start", "end"})
    one = sum(1 for p in with_pos.values() if len(p) == 1)
    none = len(res.exercises) - both - one
    L += [f"- Start and end image: **{both}** exercises; only one image: {one}; no image: **{none}** "
          f"(of {len(res.exercises)}).",
          "- Images per source: " + ", ".join(f"`{sid}` {pos} {n}" for (sid, pos), n in sorted(img_src.items())) + ".",
          "- The image files are **not in git** (this repository is public). `make fetch-media` downloads them to "
          "`exercise-db/media/`; `exercise_images.path` is relative to that folder, `source_url` is the original "
          "download URL, `sha256` the file hash.",
          "- Start and end come from the same record (same photo set). Undisputed sources and more permissive "
          "licenses are preferred when several records have images.", ""]
    no_img = sorted(e for e in res.exercises if e not in with_pos)
    pipeline_targets = sorted(set(tax.pipeline_labels.values()))
    missing_targets = [e for e in pipeline_targets if with_pos.get(e) != {"start", "end"}]
    L += [f"Pipeline-label exercises without a start+end image ({len(missing_targets)} of {len(pipeline_targets)}): "
          + (", ".join(f"`{e}`" for e in missing_targets) or "none") + "", "",
          "<details><summary>Exercises without any image</summary>", "", ", ".join(f"`{e}`" for e in no_img), "",
          "</details>", ""]

    # ---- disputed sources
    disputed = [d for d in tax.config.get("disputed_sources") or [] if d in tax.sources]
    if disputed:
        L += ["## Disputed sources", ""]
        for sid in disputed:
            n_ex = sum(1 for recs in res.ex_records.values() if any(r.source_id == sid for r in recs))
            n_only = sum(1 for recs in res.ex_records.values() if {r.source_id for r in recs} == {sid})
            n_img = sum(1 for i in res.exercise_images if i["source_id"] == sid)
            L += [f"- `{sid}` was ingested on Spottr's explicit decision although its provenance is disputed "
                  f"(it appears to be scraped from bodybuilding.com; `sources/{sid}/PROVENANCE.md`). "
                  f"It backs {n_ex} exercises ({n_only} only from this source) and supplies {n_img} images.",
                  "- Its instruction texts (copied word for word) are not used; they remain only inside "
                  "`source_records.raw_json`. Its images are not committed. Removing it is one line in "
                  "`config.yaml`; ids of exercises it created stay reserved in `id_registry.csv`.", ""]

    L += ["## Licenses and attribution", ""]
    for sid in tax.config["sources"]:
        s = tax.sources[sid]
        lic = Counter(r.d["license"] for r in res.records if r.source_id == sid and res.assignments[r.ref].exercise_id)
        L += [f"### {s['name']} (`{sid}`)", "",
              f"- License: `{s['license']}` ({s['license_url']}); commercial use: {'yes' if s['commercial_use_ok'] else 'NO'}.",
              "- Per-record licenses of ingested records: " + ", ".join(f"`{k}` {lic[k]}" for k in sorted(lic)) + ".",
              f"- Attribution to show in the app: {s['attribution'] or '(none required)'}", ""]
        if sid == "wger":
            L += ["  wger attributes each entry as \"<exercise> by <author> is licensed under <license>\". "
                  "`source_records.author` and `source_records.license` hold this per exercise; "
                  "`dist/exercises.json` repeats them under `sources`.", ""]
    L += ["## Share-alike obligations", ""]
    sa = [sid for sid in tax.config["sources"] if tax.sources[sid]["share_alike"]]
    if sa:
        L += [f"- Share-alike sources: {', '.join(f'`{s}`' for s in sa)}.",
              "- The merged database is an adaptation of their content (names, instructions, muscle tags). "
              "If it is shared outside Spottr (published, given to customers, served through an API as a data set), "
              "it must be shared under CC BY-SA 4.0 (or a compatible license) with attribution.",
              "- Showing exercises inside the app is fine with attribution; the attribution text above must be shown "
              "(e.g. on an \"About / Data sources\" screen and with the exercise detail).",
              "- Our own code that reads the data is not affected; only the data and adaptations of it are.",
              "- To get a share-alike-free subset, filter on `source_records.license` (e.g. CC0-1.0 records) "
              "or on exercises whose sources are all non-share-alike.", ""]
    else:
        L += ["None.", ""]

    # ---- skipped
    L += ["## Skipped", ""]
    excluded = tax.config.get("excluded_sources") or {}
    if excluded:
        L += ["### Sources not ingested", ""]
        for sid, why in sorted(excluded.items()):
            L += [f"- `{sid}`: {why.strip()}"]
        L += ["- Discovered candidates that were not ingested: see `reports/source_candidates.md`.", ""]
    skipped = defaultdict(list)
    for r in res.records:
        a = res.assignments[r.ref]
        if not a.exercise_id:
            skipped[a.skip_reason].append(r)
    L += ["### Source records not linked to an exercise", "",
          "They stay in `source_records` (with `exercise_id` NULL) and their muscle claims in "
          "`exercise_muscle_evidence`.", ""]
    for reason in sorted(skipped):
        recs = skipped[reason]
        L += [f"- {reason}: {len(recs)}", "", "<details><summary>Records</summary>", "",
              ", ".join(f"{r.source_id}/{r.rid} \"{r.name_en or r.name_de or ''}\"" for r in recs), "", "</details>", ""]
    if res.no_primary_fallback:
        L += ["### Exercises where voting left no primary muscle", "",
              "The muscles with the most primary votes were kept as primary and the exercise is flagged "
              "`needs_review`: " + ", ".join(f"`{e}`" for e in res.no_primary_fallback), ""]
    if res.non_english_instructions:
        L += ["### Instructions not used because they are not in English", "",
              "Another source's instructions are used where available:", ""]
        L += [f"- {s}/{rid}: \"{n}\"" for s, rid, n in res.non_english_instructions] + [""]
    if res.suspect_names:
        L += ["### Possibly non-English names in the English name field", "",
              "Kept as the source has them (not translated or renamed); worth fixing upstream:", ""]
        L += [f"- {s}/{rid}: \"{n}\"" for s, rid, n in res.suspect_names] + [""]

    # ---- rules
    L += ["## Known limitations", "",
          "- wger's \"Trapezius\" and longhaul-fitness' \"trap\" cover the whole trapezius; they map to the `traps` "
          "group (upper trapezius). On rows and rear-delt work the middle trapezius (`upper_back`) is meant, so "
          "`upper_back` is under-counted unless free-exercise-db (\"middle back\") or the pipeline table covers the exercise.",
          "- No source tags hip flexors; neck work only comes from free-exercise-db.",
          "- Records without equipment information stay separate from same-named exercises with equipment "
          "(review queue) instead of being guessed.", ""]
    L += ["## How the build decides", "",
          "- **Match key** = normalized name + load equipment. Names: lowercase, accents and punctuation stripped, "
          "abbreviations expanded (db, bb, kb, ez, rdl, ohp), synonyms and plurals unified, filler and equipment words "
          "dropped, tokens sorted (`taxonomy/name_rules.yaml`). Load equipment excludes accessories such as bench, mat "
          "and pull-up bar (`taxonomy/equipment.yaml`), because sources disagree on listing them; exercises with "
          "different load equipment are never merged. If a record has no equipment, it is taken from equipment words "
          "in its name; otherwise it stays unknown and only matches other unknowns.",
          f"- **Fuzzy matching**: rapidfuzz `token_set_ratio` between keys with the same load equipment. "
          f">= {tax.config['fuzzy']['auto_merge']}: merge, {tax.config['fuzzy']['review']}-"
          f"{tax.config['fuzzy']['auto_merge'] - 1}: review queue and separate exercise, below: new exercise. "
          "`token_set_ratio` is 100 whenever one name's tokens are a subset of the other's (\"deadlift\" vs "
          "\"romanian deadlift\"), so an auto-merge additionally requires that every differing token has a "
          "near-identical counterpart (a spelling variant). Names differing only by variation words (incline, "
          "seated, single-arm, ...) are separate exercises linked with `variation_of`; other extra words send the "
          "pair to the review queue. Records of the same source are only merged on an identical key.",
          "- **Records that cannot create an exercise**: no English name, or no primary muscle. They can still attach "
          "to an exercise on an exact name match.",
          "- **Muscle roles**: per source, the highest role it gives a muscle; across sources, the majority role, "
          "ties go to the higher role. `confidence` = sources agreeing on that role / sources with any muscle claim "
          "for the exercise. A group-level claim (\"shoulders\") counts as support for that group's specific muscles. "
          "A group row is dropped when a specific muscle of the same group is present, unless the group's role is higher.",
          "- **Reviewed mappings**: `spottr-pipeline` (the vision pipeline's own exercise -> muscle table, "
          "`backend/vision/exercises.py`) attaches through `taxonomy/pipeline_labels.yaml` and its muscle list is "
          "final for the exercises it covers (`authoritative_sources` in `config.yaml`). Weights become roles: "
          ">= 0.8 primary, >= 0.4 secondary, else stabilizer. `confidence` still shows how many sources agree.",
          "- **Movement pattern and laterality**: explicit token rules in `taxonomy/movement_rules.yaml`; NULL when "
          "no rule applies.",
          "- **Instructions**: from the record with the most permissive license (then source priority), never from a "
          "disputed source, and only if the text looks English (stopword check).",
          "- **Review queue reasons**: fuzzy score 85-94; extra words with token_sort_ratio >= 85; names differing only "
          "by a default-form word (bent-over, standing); same name where one side has no equipment; a match only "
          "through a source alias; a name whose equipment word contradicts the source's equipment.",
          "- **IDs**: `taxonomy/id_registry.csv` keeps (source, record) -> exercise id forever; rebuilds reuse it "
          "and only add rows. To resolve a review-queue row, edit its registry row: set `exercise_id` to the "
          "candidate (merge) or keep it (separate), and set `match_method` to `manual`.",
          ""]
    path.write_text("\n".join(L) + "\n", encoding="utf-8")


def write_reports(res: BuildResult, tables: dict, out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    write_review_queue(res, out_dir / "review_queue.csv")
    write_build_report(res, tables, out_dir / "build_report.md")
